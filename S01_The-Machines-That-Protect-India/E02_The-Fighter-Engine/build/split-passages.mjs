// Splits scene-length narration passages (audio/daniel/*.mp3) into the per-sentence clips the film is timed on.
// Passages are generated with a double [long pause] between clips, so the N-1 longest silences inside a passage are the
// clip boundaries. Each clip is trimmed of leading/trailing silence and written to audio/trim/<clip>.wav, then the measured
// lengths are written to narration/measured.js. usage: node build/split-passages.mjs
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const PASSAGES = {
  P01: ['d01', 'd02', 'd03'],
  P02: ['d04', 'd05', 'd06'],
  P03: ['d07', 'd08', 'd09'],
  P04: ['d10', 'd11', 'd12'],
  P05: ['d13', 'd14', 'd15'],
  P06: ['d16', 'd17', 'd18'],
  P07: ['d19', 'd20', 'd21'],
  P08: ['d22', 'd23', 'd24'],
  P09: ['d25', 'd26', 'd27'],
  P10: ['d28', 'd29', 'd30'],
  P11: ['d31', 'd32'],
  P12: ['d33', 'd34', 'd35'],
  P13: ['d36', 'd37', 'd38'],
  P14: ['d39', 'd40', 'd41'],
  P15: ['d42', 'd43', 'd44'],
  P16: ['d45', 'd46', 'd47'],
  P17: ['d48', 'd49'],
  P18: ['d50', 'd51'],
};
const SR = 48000, THRESH = '-42dB', MIN_SIL = 0.25, HEAD_PAD = 0.04, TAIL_PAD = 0.12;
const timing = readFileSync('src/timing.js', 'utf8');
const words = Object.fromEntries([...timing.matchAll(/\['(d\d+)', \d+, ("[^"]*"|'[^']*'), [\d.]+\]/g)].map((m) => [m[1], eval(m[2]).trim().split(/\s+/).length]));
const run = (args) => execFileSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', ...args]);
const duration = (f) => parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString());

function silences(file) {
  const r = spawnSync('ffmpeg', ['-hide_banner', '-nostats', '-i', file, '-af', `silencedetect=n=${THRESH}:d=${MIN_SIL}`, '-f', 'null', '-'], { encoding: 'utf8' });
  const out = []; let start = null;
  for (const line of r.stderr.split('\n')) {
    const a = /silence_start: (-?[\d.]+)/.exec(line), b = /silence_end: ([\d.]+)/.exec(line);
    if (a) start = Math.max(0, parseFloat(a[1]));
    if (b && start != null) { out.push({ start, end: parseFloat(b[1]) }); start = null; }
  }
  return out;
}

mkdirSync('audio/trim', { recursive: true });
const measured = {}, report = [];
for (const [pid, ids] of Object.entries(PASSAGES)) {
  const src = `audio/daniel/${pid}.mp3`, total = duration(src);
  const inner = silences(src).filter((s) => s.start > 0.3 && s.end < total - 0.3); // ignore lead-in and tail
  if (inner.length < ids.length - 1) throw new Error(`${pid}: found ${inner.length} silences, need ${ids.length - 1}`);
  const cuts = inner.sort((a, b) => b.end - b.start - (a.end - a.start)).slice(0, ids.length - 1).sort((a, b) => a.start - b.start).map((s) => (s.start + s.end) / 2);
  const edges = [0, ...cuts, total];
  ids.forEach((id, i) => {
    const out = `audio/trim/${id}.wav`;
    run(['-ss', String(edges[i]), '-to', String(edges[i + 1]), '-i', src,
      '-af', `silenceremove=start_periods=1:start_threshold=${THRESH}:start_silence=${HEAD_PAD},areverse,silenceremove=start_periods=1:start_threshold=${THRESH}:start_silence=${TAIL_PAD},areverse,atempo=1.12`,
      '-ar', String(SR), '-ac', '1', out]);
    measured[id] = +duration(out).toFixed(3);
    const wps = words[id] / measured[id];
    report.push({ clip: id, passage: pid, sec: measured[id], words: words[id], wps: +wps.toFixed(2), ok: wps > 1.2 && wps < 3.6 });
  });
}
writeFileSync('narration/measured.js', '// Measured clip lengths (s) of the trimmed narration takes in audio/trim. Generated by build/split-passages.mjs; edit nothing by hand.\nwindow.MEASURED_CLIPS = ' + JSON.stringify(measured) + ';\n');
const bad = report.filter((r) => !r.ok);
console.log(report.map((r) => `${r.clip} ${r.sec}s ${r.words}w ${r.wps}w/s${r.ok ? '' : '  <-- CHECK'}`).join('\n'));
console.log(`clips ${report.length}, voice ${Object.values(measured).reduce((a, b) => a + b, 0).toFixed(1)} s, suspicious ${bad.length}`);
process.exit(bad.length ? 1 : 0);
